func TestService_EnrichWithLLM(t *testing.T) {
	traffic, err := parser.ParseHAR(sampleHAR)
	require.NoError(t, err)

	// Before enrichment names should be empty
	for _, ep := range traffic.Endpoints {
		assert.Empty(t, ep.Name)
	}

	svc := service.New(mockLLM{})
	err = svc.EnrichWithLLM(traffic)
	require.NoError(t, err)

	assert.Equal(t, "listUsers", traffic.Endpoints[0].Name)
	assert.Equal(t, "createUser", traffic.Endpoints[1].Name)
	assert.Equal(t, "getPost", traffic.Endpoints[2].Name)
}

func TestGenerateRequest_Validation(t *testing.T) {
	svc := service.New(mockLLM{})

	t.Run("missing traffic", func(t *testing.T) {
		_, err := svc.Generate(models.GenerateRequest{Type: "client"})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "traffic data is required")
	})

	t.Run("invalid type", func(t *testing.T) {
		traffic, _ := parser.ParseHAR(sampleHAR)
		_, err := svc.Generate(models.GenerateRequest{
			Traffic: traffic,
			Type:    "invalid",
		})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "unsupported type")
	})

	t.Run("invalid language", func(t *testing.T) {
		traffic, _ := parser.ParseHAR(sampleHAR)
		_, err := svc.Generate(models.GenerateRequest{
			Traffic: traffic,
			Type:    "client",
			Lang:    "rust",
		})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "unsupported language")
	})
}

func TestModels_ToOpenAPI(t *testing.T) {
	traffic, err := parser.ParseHAR(sampleHAR)
	require.NoError(t, err)

	spec, err := traffic.ToOpenAPI()
	require.NoError(t, err)
	assert.Contains(t, spec, "openapi: 3.1.0")
	assert.Contains(t, spec, "/api/users")
	assert.Contains(t, spec, "listUsers")
	assert.Contains(t, spec, "createUser")
	assert.Contains(t, spec, "getPost")
}
