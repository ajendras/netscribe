//go:embed testdata/sample.har
var sampleHAR []byte

// mockLLM returns deterministic, predictable names so that golden-style
// assertions remain stable across runs. It never calls Ollama.
type mockLLM struct{}

func (mockLLM) Complete(prompt, model string) (string, error) {
	if strings.Contains(prompt, "GET") && strings.Contains(prompt, "/users") {
		return "listUsers", nil
	}
	if strings.Contains(prompt, "POST") && strings.Contains(prompt, "/users") {
		return "createUser", nil
	}
	if strings.Contains(prompt, "GET") && strings.Contains(prompt, "/posts") {
		return "getPost", nil
	}
	return "callEndpoint", nil
}

func TestParseHAR_ValidTraffic(t *testing.T) {
	traffic, err := parser.ParseHAR(sampleHAR)
	require.NoError(t, err)
	require.NotNil(t, traffic)

	assert.Equal(t, 3, len(traffic.Endpoints))
	assert.Equal(t, 5, traffic.TotalRequests)

	// Verify grouping, ordering and example capture
	assert.Equal(t, "GET", traffic.Endpoints[0].Method)
	assert.Equal(t, "/api/users", traffic.Endpoints[0].Path)
	assert.Equal(t, 2, len(traffic.Endpoints[0].Examples))

	assert.Equal(t, "POST", traffic.Endpoints[1].Method)
	assert.Equal(t, "/api/users", traffic.Endpoints[1].Path)
	assert.Equal(t, 1, len(traffic.Endpoints[1].Examples))

	// Schema inference helper works on real data
	schema := traffic.Endpoints[0].InferSchema()
	assert.Equal(t, "object", schema)
}

func TestParseHAR_ErrorCases(t *testing.T) {
	t.Run("empty bytes", func(t *testing.T) {
		_, err := parser.ParseHAR([]byte{})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "HAR file is empty")
	})

	t.Run("invalid json", func(t *testing.T) {
		_, err := parser.ParseHAR([]byte(`{ "log": "broken"`))
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "invalid HAR JSON")
	})

	t.Run("no entries", func(t *testing.T) {
		empty := []byte(`{"log":{"entries":[]}}`)
		_, err := parser.ParseHAR(empty)
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "HAR contains no entries")
	})
}

func TestFullPipeline_ClientGeneration(t *testing.T) {
	traffic, err := parser.ParseHAR(sampleHAR)
	require.NoError(t, err)

	svc := service.New(mockLLM{})

	req := models.GenerateRequest{
		Traffic: traffic,
		Type:    "client",
		Lang:    "typescript",
	}

	artifact, err := svc.Generate(req)
	require.NoError(t, err)

	assert.Equal(t, "client", artifact.Type)
	assert.Equal(t, "typescript", artifact.Language)
	assert.Equal(t, "client.ts", artifact.Filename)
	assert.Contains(t, artifact.Content, "export class ApiClient")
	assert.Contains(t, artifact.Content, "listUsers")
	assert.Contains(t, artifact.Content, "createUser")
	assert.Contains(t, artifact.Content, "getPost")
	// template header must be present
	assert.Contains(t, artifact.Content, "Code generated by NetScribe. DO NOT EDIT.")
}

