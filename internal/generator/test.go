package generator

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
	"text/template"

	"github.com/netscribe/netscribe/internal/models"
)

// GenerateTest produces a ready-to-run Go test file containing table-driven
// tests that spin up an in-memory httptest server replaying the exact
// responses captured in the HAR. The test is self-contained, uses only
// the standard library, and will pass out of the box.
func GenerateTest(traffic *models.TrafficData, lang string) (string, error) {
	if traffic == nil {
		return "", fmt.Errorf("traffic data is required")
	}
	if len(traffic.Endpoints) == 0 {
		return "", fmt.Errorf("no endpoints in traffic data")
	}

	// Default to Go tests (most common for backend validation). Other languages
	// receive the same Go test for now; language-specific test generators can
	// be added later without breaking the public API.
	return generateGoTest(traffic)
}

func generateGoTest(traffic *models.TrafficData) (string, error) {
	data := buildTestData(traffic)

	tmpl, err := template.New("go-test").Parse(goTestTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse test template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("failed to execute test template: %w", err)
	}
	return buf.String(), nil
}

type testData struct {
	Endpoints []testEndpoint
}

type testEndpoint struct {
	Name   string
	Method string
	Path   string
	Status int
	Body   string
}

func buildTestData(traffic *models.TrafficData) testData {
	var eps []testEndpoint
	for _, ep := range traffic.Endpoints {
		name := ep.Name
		if name == "" {
			name = methodName(ep.Method, ep.Path)
		}
		status := 200
		bodyStr := `{"message":"success"}`
		if len(ep.Examples) > 0 {
			ex := ep.Examples[0].Response
			status = ex.Status
			if ex.Body != nil {
				if b, err := json.Marshal(ex.Body); err == nil {
					bodyStr = string(b)
				}
			}
		}
		eps = append(eps, testEndpoint{
			Name:   name,
			Method: ep.Method,
			Path:   ep.Path,
			Status: status,
			Body:   bodyStr,
		})
	}
	return testData{Endpoints: eps}
}

const goTestTemplate = `// Code generated by NetScribe. DO NOT EDIT.
// Run with: go test -run=TestTrafficBasedAPI

package client_test

import (
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"testing"
)

func TestTrafficBasedAPI(t *testing.T) {
	// Fixtures captured from real HAR traffic.
	fixtures := map[string]struct {
		status int
		body   string
	}{
{{range .Endpoints}}
		"{{.Method}}:{{.Path}}": {
			status: {{.Status}},
			body:   {{printf "%q" .Body}},
		},
{{end}}
	}

	// Test server replays exactly the responses observed in production traffic.
	ts := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		key := r.Method + ":" + r.URL.Path
		if fix, ok := fixtures[key]; ok {
			w.Header().Set("Content-Type", "application/json")
			w.WriteHeader(fix.status)
			_, _ = w.Write([]byte(fix.body))
			return
		}
		http.Error(w, "no fixture for "+key, http.StatusNotFound)
	}))
	defer ts.Close()

	testCases := []struct {
		name       string
		method     string
		path       string
		wantStatus int
	}{
{{range .Endpoints}}
		{
			name:       "{{.Name}}",
			method:     "{{.Method}}",
			path:       "{{.Path}}",
			wantStatus: {{.Status}},
		},
{{end}}
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			req, err := http.NewRequest(tc.method, ts.URL+tc.path, nil)
			if err != nil {
				t.Fatal(err)
			}

			resp, err := http.DefaultClient.Do(req)
			if err != nil {
				t.Fatal(err)
			}
			defer resp.Body.Close()

			if resp.StatusCode != tc.wantStatus {
				t.Errorf("status code = %d; want %d", resp.StatusCode, tc.wantStatus)
			}

			// Verify the body can be decoded (matches production shape).
			var got any
			if err := json.NewDecoder(resp.Body).Decode(&got); err != nil {
				// Non-JSON responses are acceptable for some endpoints.
				t.Logf("response was not JSON: %v", err)
				return
			}
			if got == nil {
				t.Error("expected non-nil decoded body")
			}
		})
	}
}
`
