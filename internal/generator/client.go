// GenerateClient generates a complete, idiomatic HTTP client in the requested
// language using the observed traffic. Endpoint names populated by the LLM
// (or a deterministic fallback) are used for method names. Bodies are typed
// as generic (any/interface{}) because full schema inference is handled
// downstream by models.InferSchema (planned).
func GenerateClient(traffic *models.TrafficData, lang string) (string, error) {
	if traffic == nil {
		return "", fmt.Errorf("traffic data is required")
	}
	if len(traffic.Endpoints) == 0 {
		return "", fmt.Errorf("no endpoints in traffic data")
	}

	switch strings.ToLower(lang) {
	case "typescript", "ts":
		return generateTypeScriptClient(traffic)
	case "go", "golang":
		return generateGoClient(traffic)
	case "python", "py":
		return generatePythonClient(traffic)
	default:
		return "", fmt.Errorf("unsupported language for client: %s (supported: typescript, go, python)", lang)
	}
}

func generateTypeScriptClient(traffic *models.TrafficData) (string, error) {
	data := struct {
		Endpoints []endpointInfo
	}{
		Endpoints: buildEndpointInfos(traffic.Endpoints),
	}

	tmpl, err := template.New("typescript-client").Parse(tsClientTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse typescript template: %w", err)
	}

	var buf bytes.Buffer
	if err = tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("failed to execute typescript template: %w", err)
	}
	return buf.String(), nil
}

func generateGoClient(traffic *models.TrafficData) (string, error) {
	data := struct {
		Endpoints []endpointInfo
	}{
		Endpoints: buildEndpointInfos(traffic.Endpoints),
	}

	funcMap := template.FuncMap{
		"export": toExportedName,
	}
	tmpl, err := template.New("go-client").Funcs(funcMap).Parse(goClientTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse go template: %w", err)
	}

	var buf bytes.Buffer
	if err = tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("failed to execute go template: %w", err)
	}
	return buf.String(), nil
}

func generatePythonClient(traffic *models.TrafficData) (string, error) {
	data := struct {
		Endpoints []endpointInfo
	}{
		Endpoints: buildEndpointInfos(traffic.Endpoints),
	}

	tmpl, err := template.New("python-client").Parse(pythonClientTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse python template: %w", err)
	}

	var buf bytes.Buffer
	if err = tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("failed to execute python template: %w", err)
	}
	return buf.String(), nil
}

type endpointInfo struct {
	Name   string
	Method string
	Path   string
}

func buildEndpointInfos(eps []models.Endpoint) []endpointInfo {
	var out []endpointInfo
	for _, ep := range eps {
		name := ep.Name
		if name == "" {
			name = methodName(ep.Method, ep.Path)
		}
		out = append(out, endpointInfo{
			Name:   name,
			Method: ep.Method,
			Path:   ep.Path,
		})
	}
	return out
}

// methodName returns a deterministic camelCase name when the LLM has not
// supplied one.
func methodName(method, path string) string {
	if path == "" || path == "/" {
		return strings.ToLower(method)
	}
	path = strings.Trim(path, "/")
	parts := strings.Split(path, "/")
	var b strings.Builder
	b.WriteString(strings.ToLower(method))
	for _, p := range parts {
		if p == "" || strings.ContainsAny(p, "{:*}") {
			continue
		}
		clean := strings.Map(func(r rune) rune {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
				return r
			}
			return -1
		}, p)
		if clean != "" {
			runes := []rune(clean)
			runes[0] = []rune(strings.ToUpper(string(runes[0])))[0]
			b.WriteString(string(runes))
		}
	}
	name := b.String()
	if len(name) > 50 {
		name = name[:50]
	}
	return name
}

func toExportedName(name string) string {
	if name == "" {
		return "CallAPI"
	}
	r := []rune(name)
	if len(r) > 0 && unicode.IsLower(r[0]) {
		r[0] = unicode.ToUpper(r[0])
	}
	return string(r)
}

const tsClientTemplate = `// Code generated by NetScribe. DO NOT EDIT.

export class ApiClient {
  private baseURL: string;

  constructor(baseURL: string = "https://api.example.com") {
    this.baseURL = baseURL.replace(/\/+$/, "");
  }

  private async request<T = any>(
    method: string,
    path: string,
    body?: any
  ): Promise<T> {
    const url = this.baseURL + (path.startsWith("/") ? "" : "/") + path;
    const options: RequestInit = {
      method: method,
      headers: {
        "Content-Type": "application/json",
        "Accept": "application/json",
      },
    };

    if (body !== undefined && body !== null) {
      options.body = JSON.stringify(body);
    }

    const response = await fetch(url, options);

    if (!response.ok) {
      let errorMsg = ` + "`" + `HTTP error! status: ${response.status}` + "`" + `;
      try {
        const errorBody = await response.json();
        errorMsg += ` + "`" + ` - ${JSON.stringify(errorBody)}` + "`" + `;
      } catch (_) {}
      throw new Error(errorMsg);
    }

    const contentType = response.headers.get("content-type");
    if (contentType && contentType.includes("application/json")) {
      return await response.json() as T;
    }
    return await response.text() as any as T;
  }

{{range .Endpoints}}
  /**
   * {{.Method}} {{.Path}}
   */
  async {{.Name}}(body?: any): Promise<any> {
    return this.request("{{.Method}}", "{{.Path}}", body);
  }
{{end}}
}

// Example usage:
// const client = new ApiClient("https://your-service.com");
// const result = await client.{{(index .Endpoints 0).Name}}();
`

const goClientTemplate = `// Code generated by NetScribe. DO NOT EDIT.

package client

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"strings"
	"time"
)

type Client struct {
	baseURL    string
	httpClient *http.Client
}

func New(baseURL string) *Client {
	if baseURL == "" {
		baseURL = "https://api.example.com"
	}
	return &Client{
		baseURL: strings.TrimRight(baseURL, "/"),
		httpClient: &http.Client{
			Timeout: 30 * time.Second,
		},
	}
}

{{range .Endpoints}}
// {{.Method}} {{.Path}} calls the {{.Name}} endpoint.
func (c *Client) {{export .Name}}(ctx context.Context, payload interface{}) (interface{}, error) {
	url := c.baseURL + "{{.Path}}"
	var body io.Reader
	if payload != nil {
		b, err := json.Marshal(payload)
		if err != nil {
			return nil, fmt.Errorf("failed to marshal payload: %w", err)
		}
		body = bytes.NewReader(b)
	}

	req, err := http.NewRequestWithContext(ctx, "{{.Method}}", url, body)
	if err != nil {
		return nil, fmt.Errorf("failed to create request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "application/json")

	resp, err := c.httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("request failed: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 300 {
		bodyBytes, _ := io.ReadAll(resp.Body)
		return nil, fmt.Errorf("unexpected status %d: %s", resp.StatusCode, string(bodyBytes))
	}

	var result interface{}
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return nil, fmt.Errorf("failed to decode response: %w", err)
	}
	return result, nil
}
{{end}}
`

